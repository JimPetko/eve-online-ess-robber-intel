#!/usr/bin/env node
// Decisions for run-calibration.sh, kept here so they can be tested.
// Usage: node calibration.mjs <command> [args]; file arguments are paths, "-" is stdin.
import { readFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { syncWorkItem } from "./plane.mjs";

export const REQUIRED_CHECKS = ["check", "tests-required"];

/** The calendar month before `now`, in UTC, as YYYY-MM. */
export function targetMonth(now) {
  const previous = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth() - 1, 1));
  return previous.toISOString().slice(0, 7);
}

/** The figures a generated `isk-per-npc-kill.generated.ts` was calibrated with, or null. */
export function calibrationSummary(source) {
  const month = /\bmonth: "(\d{4}-\d{2})"/.exec(source)?.[1];
  if (month === undefined) return null;
  const number = (key) => Number(new RegExp(`\\b${key}: (\\d+)`).exec(source)?.[1]);
  return { month, fallback: number("fallback"), hoursSampled: number("hoursSampled"), hoursInMonth: number("hoursInMonth") };
}

/** True when calibrate-bounties failed only because CCP has not published that month's MER yet. */
export function merNotPublished(output) {
  return /EVEOnline_MER_\d{6}\.zip: 404\b/.test(output);
}

/** The state of the calibration PR from `gh pr list --json number,state,url`: MERGED, OPEN or NONE. */
export function prState(prs) {
  const pr = prs.find((p) => p.state === "MERGED") ?? prs.find((p) => p.state === "OPEN");
  return pr === undefined ? { state: "NONE" } : { state: pr.state, url: pr.url };
}

/** passed, failed or pending, from `gh pr view --json statusCheckRollup`. */
export function checksState({ statusCheckRollup = [] }) {
  const checks = statusCheckRollup.map((c) =>
    c.__typename === "StatusContext"
      ? { name: c.context, done: c.state !== "PENDING" && c.state !== "EXPECTED", ok: c.state === "SUCCESS" }
      : { name: c.name, done: c.status === "COMPLETED", ok: ["SUCCESS", "SKIPPED", "NEUTRAL"].includes(c.conclusion) },
  );
  if (checks.some((c) => c.done && !c.ok)) return "failed";
  if (checks.some((c) => !c.done) || !REQUIRED_CHECKS.every((n) => checks.some((c) => c.name === n))) return "pending";
  return "passed";
}

export function commitMessage({ month, fallback, hoursSampled, hoursInMonth }) {
  return `chore(calibration): recalibrate ISK per NPC kill for ${month}

Fallback (pooled): ${String(fallback)} ISK per NPC kill.
Hours sampled: ${String(hoursSampled)}/${String(hoursInMonth)}.
`;
}

export function prBody({ repo, before, after }) {
  const was = before === null ? "" : ` (was ${String(before.fallback)} for ${before.month})`;
  return `## Why
CCP has published the Monthly Economic Report for ${after.month}, so ISK per NPC kill is recalibrated from it. Method: [docs/research/bounty-calibration.md](https://github.com/${repo}/blob/main/docs/research/bounty-calibration.md).

## What changed
- \`src/domain/isk-per-npc-kill.generated.ts\` regenerated by \`node scripts/calibrate-bounties.mjs ${after.month}\`.
- Fallback (pooled): ${String(after.fallback)} ISK per NPC kill${was}.
- Hours sampled: ${String(after.hoursSampled)}/${String(after.hoursInMonth)}.

## Verification
Labelled \`no-tests-needed\`: the change is generated data, and the existing tests check every value's plausibility.

Opened by \`ops/calibration/run-calibration.sh\`.
`;
}

const read = (path) => readFileSync(path === "-" ? 0 : path, "utf8");
const summaryOf = (path) => {
  const summary = calibrationSummary(read(path));
  if (summary === null) throw new Error(`${path} has no calibration month`);
  return summary;
};

const commands = {
  "target-month": () => targetMonth(new Date()),
  "calibrated-month": (file = "-") => calibrationSummary(read(file))?.month ?? "",
  "mer-not-published": (file = "-") => (merNotPublished(read(file)) ? "yes" : "no"),
  "pr-state": (file = "-") => {
    const { state, url = "" } = prState(JSON.parse(read(file)));
    return `${state} ${url}`.trim();
  },
  "checks-state": (file = "-") => checksState(JSON.parse(read(file))),
  "commit-message": (file) => commitMessage(summaryOf(file)),
  "pr-body": (repo, after, before) => prBody({ repo, after: summaryOf(after), before: before ? calibrationSummary(read(before)) : null }),
  "plane-sync": async (month, prUrl, status, dryRun) => {
    const result = await syncWorkItem({
      baseUrl: process.env.PLANE_BASE_URL || "http://192.168.0.187:8090",
      apiKey: process.env.PLANE_API_KEY ?? "",
      workspace: process.env.PLANE_WORKSPACE_SLUG ?? "",
      project: process.env.PLANE_PROJECT_IDENTIFIER || "ESS",
      month,
      prUrl,
      done: status === "done",
      dryRun: dryRun === "--dry-run",
    });
    return `Plane work item ${result.action}${result.id ? ` (${result.id})` : ""}`;
  },
};

async function main([command, ...args]) {
  const run = commands[command];
  if (run === undefined) {
    console.error(`usage: node calibration.mjs <${Object.keys(commands).join("|")}> [args]`);
    return 2;
  }
  try {
    process.stdout.write(`${await run(...args)}\n`.replace(/\n\n$/, "\n"));
    return 0;
  } catch (error) {
    console.error(`calibration.mjs ${command}: ${error instanceof Error ? error.message : String(error)}`);
    return 1;
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) process.exit(await main(process.argv.slice(2)));
